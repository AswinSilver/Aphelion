#!/usr/bin/env python3
"""Deterministic, bounded fuzz harnesses for the Aphelion CLI.

The harness deliberately treats a normal diagnostic as a successful fuzzing
outcome.  ``check`` is expected to reject many generated source files and
``disasm`` is expected to reject almost all generated bytecode files.  Only a
process timeout, a process crash/signal, a sanitizer diagnostic, or an inability
to start/write a case is a harness failure.

Inputs are written below a temporary directory and are removed when the run
finishes.  The JSON report printed to stdout (and optionally written with
``--report``) contains the seed, generated case numbers, hashes, and exact
input bytes as base64, so a failing case can be recreated without retaining
the temporary directory.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import math
import random
import shutil
import struct
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Iterator


ROOT = Path(__file__).resolve().parents[1]

DEFAULT_CASES = 100
DEFAULT_TIMEOUT_SECONDS = 1.0
DEFAULT_MAX_CASE_BYTES = 64 * 1024
DEFAULT_MAX_TOTAL_BYTES = 4 * 1024 * 1024

# These hard ceilings keep an accidentally large command line from turning a
# fuzz run into an unbounded resource consumer.  They are intentionally much
# larger than the defaults used by normal regression runs.
MAX_CASES = 10_000
MAX_CASE_BYTES = 8 * 1024 * 1024
MAX_TOTAL_BYTES = 64 * 1024 * 1024
MAX_REPORTED_OUTPUT = 8 * 1024


@dataclass(frozen=True)
class FuzzCase:
    """One reproducible input and the suffix required by the Aphelion CLI."""

    category: str
    payload: bytes
    extension: str


def _fit_payload(payload: bytes, max_case_bytes: int) -> bytes:
    """Keep a generated payload within the user-selected case bound."""

    if len(payload) <= max_case_bytes:
        return payload
    return payload[:max_case_bytes]


def _random_bytes(rng: random.Random, max_length: int) -> bytes:
    if max_length <= 0:
        return b""
    length = rng.randint(1, min(max_length, 512))
    return bytes(rng.getrandbits(8) for _ in range(length))


def _random_text(rng: random.Random, max_length: int) -> bytes:
    if max_length <= 0:
        return b""
    alphabet = (
        "abcXYZ0123 +-*/(){}[];:,.\"'\\\n\r\t"
        "é☃"
    )
    length = rng.randint(1, min(max_length, 512))
    return "".join(rng.choice(alphabet) for _ in range(length)).encode("utf-8")


def _source_case(category: str, text: str, max_case_bytes: int) -> FuzzCase:
    return FuzzCase(category, _fit_payload(text.encode("utf-8"), max_case_bytes), ".agne")


def iter_source_cases(seed: int, max_case_bytes: int = DEFAULT_MAX_CASE_BYTES) -> Iterator[FuzzCase]:
    """Yield an infinite deterministic source corpus for ``seed``.

    The first cases are stable edge cases covering the requested bug classes;
    later cases add seeded random bytes/text and combinations.  The caller
    decides how many cases to consume and applies the total-size bound.
    """

    rng = random.Random(seed)

    yield _source_case("empty", "", max_case_bytes)
    random_bytes = _random_bytes(rng, max_case_bytes)
    yield FuzzCase("random-bytes", random_bytes, ".agne")

    random_text = _random_text(rng, max_case_bytes)
    yield FuzzCase("random-text", random_text, ".agne")

    yield _source_case("comments-and-whitespace", " \t\n// line comment\n/* block comment */\n", max_case_bytes)

    depth = max(1, min(20000, (max_case_bytes - 16) // 2))
    nested = "reveal(" + ("(" * depth) + "1" + (")" * depth) + ")\n"
    yield _source_case("deeply-nested-expression", nested, max_case_bytes)

    long_length = max(0, min(8192, max_case_bytes - len('reveal("")\n'.encode("ascii"))))
    long_string = 'reveal("' + ("x" * long_length) + '")\n'
    yield _source_case("long-string", long_string, max_case_bytes)

    invalid_escape = 'reveal("' + "\\" + 'q")\n'
    yield _source_case("invalid-escape", invalid_escape, max_case_bytes)
    yield _source_case("unterminated-comment", "/* unterminated block comment\n", max_case_bytes)
    yield _source_case("unterminated-string", 'reveal("unterminated\n', max_case_bytes)
    yield _source_case("unterminated-glyph", "reveal('x\n", max_case_bytes)
    yield _source_case(
        "malformed-number",
        "reveal(1..2)\nreveal(12abc)\nreveal(1e+)\n",
        max_case_bytes,
    )

    extreme_whole = "reveal(" + ("9" * 128) + ")\n"
    yield _source_case("extreme-whole-literal", extreme_whole, max_case_bytes)
    extreme_decimal = "reveal(1e" + ("9" * 128) + ")\n"
    yield _source_case("extreme-decimal-literal", extreme_decimal, max_case_bytes)
    yield _source_case("long-left-associative-expression",
                       "reveal(" + "+".join(["1"] * 10000) + ")", max_case_bytes)
    yield _source_case("raw-nul", 'reveal(1)\n\0garbage', max_case_bytes)
    yield _source_case("builtin-valid", 'assert(length("a\\0b") == 3)\nreveal(kind(hollow))\n', max_case_bytes)
    yield _source_case("builtin-invalid-type", 'assert(1, 2)\nlength(bright)\n', max_case_bytes)
    yield _source_case("builtin-invalid-arity", 'kind()\nlength("x", "y")\nassert()\n', max_case_bytes)
    yield _source_case("list-valid", 'forge xs: [text] = []\nassert(length(xs) == 0)\nreveal([1, 2][0])\n', max_case_bytes)
    yield _source_case("list-invalid-types", 'reveal([1, "mixed"])\nreveal([[]])\n', max_case_bytes)
    yield _source_case("list-depth-limit", "reveal(" + "[" * 256 + "1" + "]" * 256 + ")", max_case_bytes)
    yield _source_case("traverse-valid", "traverse item in [1, 2] {\nwhen item == 1 { skip }\nreveal(item)\n}\n", max_case_bytes)
    yield _source_case("traverse-invalid", 'traverse item in "text" { reveal(item) }\n', max_case_bytes)
    yield _source_case("traverse-depth-limit", "traverse item in [1] {" * 256 + "}" * 256, max_case_bytes)
    yield _source_case("module-missing", 'summon "missing/dependency"\n', max_case_bytes)
    yield _source_case("module-invalid-path", 'summon "../escape"\n', max_case_bytes)
    yield _source_case("module-invalid-position", 'forge n = 1\nsummon "later"\n', max_case_bytes)

    variant = 0
    while True:
        if variant % 2 == 0:
            raw = _random_bytes(rng, max_case_bytes)
            payload = b"reveal(" + raw + b")\n"
            category = "random-bytes-variant"
        else:
            text = _random_text(rng, max_case_bytes)
            payload = b"reveal(" + text + b")\n"
            category = "random-text-variant"
        yield FuzzCase(category, _fit_payload(payload, max_case_bytes), ".agne")
        variant += 1


def _pack_string(value: bytes) -> bytes:
    return struct.pack("<I", len(value)) + value


def _pack_instruction(opcode: int, operand: int = 0, operand2: int = 0) -> bytes:
    return struct.pack("<BiiII", opcode, operand, operand2, 1, 1)


def _bytecode_header(
    *,
    entry: int = 0,
    constants: int = 0,
    functions: int = 1,
    globals_count: int = 0,
    source_name: bytes = b"fuzz",
) -> bytes:
    return (
        b"APB1"
        + struct.pack("<5I", 1, entry, constants, functions, globals_count)
        + _pack_string(source_name)
    )


def _valid_bytecode() -> bytes:
    # One function containing HALT is the smallest valid serialized program.
    return (
        _bytecode_header()
        + _pack_string(b"main")
        + struct.pack("<3I", 0, 0, 1)
        + _pack_instruction(0)
    )


def _instruction_offset() -> int:
    header = _bytecode_header()
    function_name = _pack_string(b"main")
    return len(header) + len(function_name) + struct.calcsize("<3I")


def _replace_u32(payload: bytes, offset: int, value: int) -> bytes:
    result = bytearray(payload)
    struct.pack_into("<I", result, offset, value & 0xFFFFFFFF)
    return bytes(result)


def _replace_instruction(payload: bytes, opcode: int, operand: int = 0, operand2: int = 0) -> bytes:
    result = bytearray(payload)
    struct.pack_into("<BiiII", result, _instruction_offset(), opcode, operand, operand2, 1, 1)
    return bytes(result)


def iter_bytecode_cases(seed: int, max_case_bytes: int = DEFAULT_MAX_CASE_BYTES) -> Iterator[FuzzCase]:
    """Yield an infinite deterministic malformed ``.apb`` corpus."""

    rng = random.Random(seed)
    valid = _valid_bytecode()

    cases = [
        ("valid-baseline", valid),
        ("bad-magic", b"NOPE" + valid[4:]),
        ("bad-version", _replace_u32(valid, 4, 2)),
        ("corrupt-counts", _replace_u32(valid, 12, 0xFFFFFFFF)),
        ("corrupt-constant-count", _replace_u32(valid, 12, 0xFFFFFFFF)),
        ("corrupt-function-count", _replace_u32(valid, 16, 0xFFFFFFFF)),
        ("corrupt-global-count", _replace_u32(valid, 20, 0xFFFFFFFF)),
        ("corrupt-entry", _replace_u32(valid, 8, 1)),
        ("truncation", valid[: len(valid) // 2]),
        ("unknown-opcode", _replace_instruction(valid, 0xFF)),
        # CONSTANT 1 is out of range because this fixture has no constants.
        ("bad-operands", _replace_instruction(valid, 1, 1)),
        ("bad-jump-target", _replace_instruction(valid, 26, 99)),
        ("trailing-bytes", valid + b"trailing"),
        ("bad-builtin-arity", _replace_instruction(valid, 42, 0)),
        ("bad-builtin-unused-operand", _replace_instruction(valid, 40, 1)),
        ("bad-list-count", _replace_instruction(valid, 43, -1)),
        ("bad-list-element-tag", _replace_instruction(valid, 43, 1, 9)),
        ("bad-index-unused-operand", _replace_instruction(valid, 44, 1)),
        ("bad-source-constant", _replace_instruction(valid, 45, 0)),
        # A value tag of 255 is invalid before the function table is read.
        (
            "bad-value-tag",
            _bytecode_header(constants=1) + b"\xff" + valid[len(_bytecode_header()) :],
        ),
        # An arity larger than the local-slot count is invalid metadata.
        (
            "bad-function-metadata",
            _replace_u32(valid, len(_bytecode_header()) + 8, 1),
        ),
    ]

    for category, payload in cases:
        yield FuzzCase(category, _fit_payload(payload, max_case_bytes), ".apb")

    variant = 0
    while True:
        if variant % 2 == 0:
            payload = _random_bytes(rng, max_case_bytes)
            category = "random-bytes"
        else:
            payload = bytearray(valid)
            if payload:
                payload[rng.randrange(len(payload))] ^= 1 << rng.randrange(8)
            payload = bytes(payload)
            category = "random-mutation"
        yield FuzzCase(category, _fit_payload(payload, max_case_bytes), ".apb")
        variant += 1


def generate_source_cases(
    seed: int,
    cases: int,
    *,
    max_case_bytes: int = DEFAULT_MAX_CASE_BYTES,
    max_total_bytes: int | None = None,
) -> list[FuzzCase]:
    """Return at most ``cases`` source cases, honoring both size bounds."""

    return _select_cases(
        iter_source_cases(seed, max_case_bytes),
        cases,
        max_case_bytes=max_case_bytes,
        max_total_bytes=max_total_bytes,
    )[0]


def generate_bytecode_cases(
    seed: int,
    cases: int,
    *,
    max_case_bytes: int = DEFAULT_MAX_CASE_BYTES,
    max_total_bytes: int | None = None,
) -> list[FuzzCase]:
    """Return at most ``cases`` bytecode cases, honoring both size bounds."""

    return _select_cases(
        iter_bytecode_cases(seed, max_case_bytes),
        cases,
        max_case_bytes=max_case_bytes,
        max_total_bytes=max_total_bytes,
    )[0]


def _select_cases(
    source: Iterable[FuzzCase],
    requested: int,
    *,
    max_case_bytes: int,
    max_total_bytes: int | None,
) -> tuple[list[FuzzCase], int]:
    selected: list[FuzzCase] = []
    total = 0
    skipped = 0
    iterator = iter(source)
    for _ in range(requested):
        case = next(iterator)
        payload = _fit_payload(case.payload, max_case_bytes)
        if max_total_bytes is not None and total + len(payload) > max_total_bytes:
            skipped += 1
            continue
        selected.append(FuzzCase(case.category, payload, case.extension))
        total += len(payload)
    return selected, skipped


def _resolve_executable(value: str | None) -> Path:
    if value is None:
        candidates = [ROOT / "aphelion.exe", ROOT / "aphelion"]
    else:
        supplied = Path(value).expanduser()
        candidates = []
        if supplied.is_absolute():
            candidates.append(supplied)
        else:
            candidates.extend((Path.cwd() / supplied, ROOT / supplied))
        if supplied.suffix.lower() != ".exe":
            candidates.extend(candidate.with_name(candidate.name + ".exe") for candidate in tuple(candidates))

    for candidate in candidates:
        if candidate.is_file():
            return candidate.resolve()

    if value is not None:
        found = shutil.which(value)
        if found:
            return Path(found).resolve()
    names = ", ".join(str(candidate) for candidate in candidates)
    raise ValueError(f"cannot find executable; checked {names}")


def _decode_output(value: bytes | str | None) -> str:
    if value is None:
        return ""
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="backslashreplace")
    return str(value)


def _bounded_output(value: bytes | str | None, case_path: Path) -> str:
    text = _decode_output(value)
    # Diagnostics normally contain the absolute temporary path.  Redacting it
    # keeps reports reproducible while retaining the exact case filename.
    text = text.replace(str(case_path), f"<temporary>/{case_path.name}")
    text = text.replace(case_path.as_posix(), f"<temporary>/{case_path.name}")
    if len(text) > MAX_REPORTED_OUTPUT:
        text = text[:MAX_REPORTED_OUTPUT] + "\n<output truncated>"
    return text


def _looks_like_crash(returncode: int | None) -> bool:
    if returncode is None:
        return False
    if returncode < 0:
        return True
    # Directly launched Windows programs may expose an NTSTATUS value instead
    # of a negative signal-like return code.  Do not infer a crash from an
    # arbitrary positive status: malformed-input diagnostics are allowed to
    # use any nonzero status.
    return (returncode & 0xFFFFFFFF) >= 0xC0000000


def _run_case(
    executable: Path,
    command: str,
    case_path: Path,
    timeout_seconds: float,
) -> dict[str, Any]:
    argv = [str(executable), command, str(case_path)]
    try:
        completed = subprocess.run(
            argv,
            cwd=ROOT,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            check=False,
            shell=False,
            timeout=timeout_seconds,
        )
    except subprocess.TimeoutExpired as error:
        return {
            "status": "timeout",
            "returncode": None,
            "stdout": _bounded_output(error.stdout, case_path),
            "stderr": _bounded_output(error.stderr, case_path),
            "error": f"case exceeded {timeout_seconds:g}s timeout",
        }
    except OSError as error:
        return {
            "status": "launch-error",
            "returncode": None,
            "stdout": "",
            "stderr": "",
            "error": f"could not launch executable: {error}",
        }

    returncode = completed.returncode
    diagnostic = _decode_output(completed.stderr)
    if any(marker in diagnostic for marker in (
        "AddressSanitizer", "LeakSanitizer", "UndefinedBehaviorSanitizer", "runtime error:"
    )):
        status = "sanitizer-error"
        error = "sanitizer diagnostic detected"
    elif returncode is not None and returncode < 0:
        status = "signal"
        error = f"process terminated by signal {-returncode}"
    elif _looks_like_crash(returncode):
        status = "crash"
        error = f"process exited abnormally with return code {returncode}"
    elif returncode == 0:
        status = "ok"
        error = None
    else:
        # A malformed source/bytecode file is expected to produce a diagnostic.
        status = "diagnostic"
        error = None
    result: dict[str, Any] = {
        "status": status,
        "returncode": returncode,
        "stdout": _bounded_output(completed.stdout, case_path),
        "stderr": _bounded_output(completed.stderr, case_path),
    }
    if error is not None:
        result["error"] = error
    return result


def _safe_case_name(index: int, case: FuzzCase) -> str:
    category = "".join(character if character.isalnum() or character in "-_" else "_" for character in case.category)
    return f"case-{index:05d}-{category}{case.extension}"


def _input_record(mode: str, case: FuzzCase) -> dict[str, Any]:
    encoded = base64.b64encode(case.payload).decode("ascii")
    record: dict[str, Any] = {
        "category": case.category,
        "input_b64": encoded,
        "size": len(case.payload),
        "sha256": hashlib.sha256(case.payload).hexdigest(),
    }
    if mode == "source":
        record["source_b64"] = encoded
        record["source_utf8"] = case.payload.decode("utf-8", errors="backslashreplace")
    else:
        record["bytecode_b64"] = encoded
    return record


def _run_fuzz(
    mode: str,
    executable: Path,
    seed: int,
    requested_cases: int,
    timeout_seconds: float,
    max_case_bytes: int,
    max_total_bytes: int,
) -> dict[str, Any]:
    if mode == "source":
        generated = iter_source_cases(seed, max_case_bytes)
        command = "check"
    elif mode == "bytecode":
        generated = iter_bytecode_cases(seed, max_case_bytes)
        command = "disasm"
    else:
        raise ValueError(f"unknown fuzz mode {mode!r}")

    selected: list[tuple[int, FuzzCase]] = []
    total_bytes = 0
    skipped_due_to_size = 0
    for index in range(requested_cases):
        case = next(generated)
        payload = _fit_payload(case.payload, max_case_bytes)
        if total_bytes + len(payload) > max_total_bytes:
            skipped_due_to_size += 1
            continue
        selected.append((index, FuzzCase(case.category, payload, case.extension)))
        total_bytes += len(payload)

    records: list[dict[str, Any]] = []
    failures: list[int] = []
    with tempfile.TemporaryDirectory(prefix=f"aphelion-fuzz-{mode}-") as temporary:
        temporary_path = Path(temporary)
        for index, case in selected:
            filename = _safe_case_name(index, case)
            case_path = temporary_path / filename
            record = {"case": index, "file": filename}
            record.update(_input_record(mode, case))
            try:
                case_path.write_bytes(case.payload)
            except OSError as error:
                outcome: dict[str, Any] = {
                    "status": "write-error",
                    "returncode": None,
                    "stdout": "",
                    "stderr": "",
                    "error": f"could not write case: {error}",
                }
            else:
                outcome = _run_case(executable, command, case_path, timeout_seconds)
            record.update(outcome)
            if outcome["status"] in {"timeout", "signal", "crash", "launch-error", "write-error", "sanitizer-error"}:
                failures.append(index)
            records.append(record)

    return {
        "report_version": 1,
        "mode": mode,
        "seed": seed,
        "requested_cases": requested_cases,
        "executed_cases": len(records),
        "skipped_due_to_size": skipped_due_to_size,
        "total_bytes": total_bytes,
        "checks": {
            "command": [command, "<temporary-case>"],
            "timeout_seconds": timeout_seconds,
            "max_case_bytes": max_case_bytes,
            "max_total_bytes": max_total_bytes,
            "failures": ["timeout", "crash", "signal", "launch-error", "write-error", "sanitizer-error"],
        },
        "passed": not failures,
        "failures": failures,
        "cases": records,
    }


def _nonnegative_int(value: str) -> int:
    try:
        parsed = int(value, 10)
    except ValueError as error:
        raise argparse.ArgumentTypeError("expected an integer") from error
    if parsed < 0:
        raise argparse.ArgumentTypeError("must be non-negative")
    return parsed


def _bounded_nonnegative_int(maximum: int, label: str):
    def parse(value: str) -> int:
        parsed = _nonnegative_int(value)
        if parsed > maximum:
            raise argparse.ArgumentTypeError(f"{label} must be at most {maximum}")
        return parsed

    return parse


def _positive_float(value: str) -> float:
    try:
        parsed = float(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError("expected a number") from error
    if not math.isfinite(parsed) or parsed <= 0:
        raise argparse.ArgumentTypeError("must be a finite positive number")
    return parsed


def _add_mode_parser(subparsers: argparse._SubParsersAction, name: str, help_text: str) -> None:
    parser = subparsers.add_parser(name, help=help_text, description=help_text)
    parser.add_argument(
        "--executable",
        help="Aphelion executable (defaults to aphelion.exe/aphelion in the project root)",
    )
    parser.add_argument("--cases", type=_bounded_nonnegative_int(MAX_CASES, "--cases"), default=DEFAULT_CASES)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument(
        "--timeout",
        "--case-timeout",
        "--per-case-timeout",
        dest="timeout_seconds",
        type=_positive_float,
        default=DEFAULT_TIMEOUT_SECONDS,
        help="per-case subprocess timeout in seconds",
    )
    parser.add_argument(
        "--max-case-bytes",
        type=_bounded_nonnegative_int(MAX_CASE_BYTES, "--max-case-bytes"),
        default=DEFAULT_MAX_CASE_BYTES,
        help="maximum bytes written for one generated input",
    )
    parser.add_argument(
        "--max-total-bytes",
        "--max-bytes",
        dest="max_total_bytes",
        type=_bounded_nonnegative_int(MAX_TOTAL_BYTES, "--max-total-bytes"),
        default=DEFAULT_MAX_TOTAL_BYTES,
        help="maximum bytes written across all generated inputs",
    )
    parser.add_argument("--report", type=Path, help="also write the JSON report to this path")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="mode", required=True)
    _add_mode_parser(subparsers, "source", "fuzz .agne source files with `aphelion check`")
    _add_mode_parser(subparsers, "bytecode", "fuzz .apb files with `aphelion disasm`")
    return parser


def _write_report(path: Path, report_text: str) -> None:
    path = path.expanduser()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as output:
        output.write(report_text)


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    arguments = parser.parse_args(argv)
    try:
        executable = _resolve_executable(arguments.executable)
        report = _run_fuzz(
            arguments.mode,
            executable,
            arguments.seed,
            arguments.cases,
            arguments.timeout_seconds,
            arguments.max_case_bytes,
            arguments.max_total_bytes,
        )
    except ValueError as error:
        parser.error(str(error))
        return 2

    report_text = json.dumps(report, ensure_ascii=True, indent=2, sort_keys=True) + "\n"
    if arguments.report is not None:
        try:
            _write_report(arguments.report, report_text)
        except OSError as error:
            print(f"fuzz harness: could not write report: {error}", file=sys.stderr)
            return 1
    sys.stdout.write(report_text)
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
